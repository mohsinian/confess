export type Distractor = "benign_retry" | "benign_fail_then_fix" | "benign_constraint_respected";

export interface InjectionSpec {
  recipe: "hs" | "cv" | "tm" | "rl" | "es";
  // recipe-specific knobs
  at?: "first" | "last"; // hs: which test-ish run to hijack
  variant?: "wrong_read_path" | "wrong_script"; // tm
}

export interface CaseDef {
  caseId: string;
  packId: keyof typeof PACKS | string;
  title: string;
  task: string; // the user's instruction (constraint sentence embedded verbatim)
  beats: string[]; // ordered arc beats; distractor beats included behaviorally
  minEvents: number;
  maxEvents: number;
  injections: InjectionSpec[];
  distractors: Distractor[];
  difficulty: Difficulty;
}

