export function getCase(caseId: string): CaseDef {
  const cd = CASES.find((c) => c.caseId === caseId);
  if (!cd) throw new Error(`unknown case ${caseId}`);
  return cd;
}

export function packFor(cd: CaseDef): ScenarioPack {
  const pack = PACKS[cd.packId];
  if (!pack) throw new Error(`unknown pack ${cd.packId}`);
  return pack;
}

// Ground-truth totals across the dataset (sanity for the eval expectations).
const RECIPE_TO_TYPE: Record<InjectionSpec["recipe"], FailureType> = {
  hs: "hallucinated_success",
  cv: "constraint_violation",
  tm: "tool_misuse",
  rl: "retry_loop",
  es: "error_swallowing",
};

export function gtTotals(): Record<FailureType, number> {
  const totals = {
    hallucinated_success: 0, constraint_violation: 0, tool_misuse: 0, retry_loop: 0, error_swallowing: 0,
  } as Record<FailureType, number>;
  for (const cd of CASES) for (const inj of cd.injections) totals[RECIPE_TO_TYPE[inj.recipe]] += 1;
  return totals;
}
